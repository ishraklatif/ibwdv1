#!/usr/bin/env python3
"""Combine per-repository adjudication records (adjudicate.py output) and the legacy kit records into one file.

Usage: combine_adjudications.py OUT.json legacy.json repo_records.json [repo_records.json ...]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

out, legacy, *repo_files = sys.argv[1:]
records = []
for f in repo_files:
    records += json.loads(Path(f).read_text())["records"]
records += json.loads(Path(legacy).read_text())["records"]
doc = {
    "purpose": "Individual, evidenced adjudications of every raw disagreement in resolved edges and every supported-scope miss. Records are generated by "
               "benchmarks/tools/adjudicate.py from verified source/oracle evidence; legacy records are the earlier kit-candidate-oracle findings converted to this schema.",
    "schema": ["repo", "repo_sha", "source", "target", "relation", "file", "line", "kind", "verdict", "category", "explanation", "evidence"],
    "verdicts": {
        "ibwd_defect": "IBWD is wrong (defects that were fixed are in the commit history, not listed here)",
        "oracle_error": "the oracle's view is wrong or missing; IBWD's edge is correct",
        "legitimate_out_of_scope": "a real but possible/undecidable target outside the supported scope; stays in the broader denominator; NOT counted as proven correct",
        "unresolved_disagreement": "cause not verified; never counted as correct",
    },
    "supersedes": "benchmarks/adjudications/sprint_3_adjudications.json (its scip-python-pass entries were made under the earlier adapter and are re-derived by the records here)",
    "records": records,
}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
from collections import Counter
print(len(records), dict(Counter(r["verdict"] for r in records)))
